// Builds the beta test page (public/learning-new-c.html) from the stable
// academy page. The beta page shows missions marked beta: true, is noindex and
// has no canonical/OG tags. Run after editing interactive-learning.html:
//   node scripts/make-beta.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../public/interactive-learning.html', import.meta.url);
const dest = new URL('../public/learning-new-c.html', import.meta.url);
let html = readFileSync(src, 'utf8');
const swap = (from, to) => {
  if (!from.test(html)) throw new Error(`make-beta: pattern not found: ${from}`);
  html = html.replace(from, to);
};
swap(/<title>[^<]*<\/title>/, '<title>Terminal Academy (Beta)</title>\n<meta name="robots" content="noindex, nofollow">');
html = html.replace(/<link rel="canonical"[^>]*>\n?/, '').replace(/<meta (property="og:[^"]*"|name="twitter:[^"]*")[^>]*>\n?/g, '');
swap(/<body>/, '<body data-channel="beta">');
swap(/(<span class="topic-num" id="topicNum">)/, '<span class="beta-badge" title="Test version: new lessons before release">BETA</span>$1');
swap(/^<!DOCTYPE html>\n/i, '<!DOCTYPE html>\n<!-- GENERATED by scripts/make-beta.mjs from interactive-learning.html. Do not edit by hand. -->\n');
writeFileSync(dest, html);
console.log('wrote public/learning-new-c.html');
